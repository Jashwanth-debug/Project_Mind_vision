export function getClinicianById(id) {
  return INITIAL_CLINICIANS.find(c => c.id === id) || null;
}

export function getCliniciansBySpecialty(specialty) {
  if (!specialty || specialty === 'ALL') return INITIAL_CLINICIANS;
  const specLower = specialty.toLowerCase();
  return INITIAL_CLINICIANS.filter(c => 
    c.specialties.some(s => s.toLowerCase().includes(specLower)) ||
    (c.specialization && c.specialization.toLowerCase().includes(specLower))
  );
}

export function getProBonoClinicians() {
  return INITIAL_CLINICIANS.filter(c => c.ratePerMinute === 0 || c.consultationFee === 0);
}
